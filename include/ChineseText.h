inline std::string zhGroupText(std::string_view english) {
    for (std::size_t i = 0; i < creatureGroups.size(); ++i)
        if (creatureGroups[i] == english) return std::string(zhGroupName(i));
    return std::string(english);
}
inline std::string_view zhAffinityName(std::size_t index) {
    return index < attributeNamesZh.size() ? attributeNamesZh[index] : std::string_view{};
}

inline std::string_view zhRarity(std::string_view value) {
    if (value == "Common") return "普通";
    if (value == "Rare") return "稀有";
    if (value == "Epic") return "史诗";
    if (value == "Legendary") return "传说";
    return value;
}

